#!/usr/bin/env python3
"""Tool class x tier matrix from data/items/items.json.

  python3 tools/tool_tiers.py            write design/TOOL_TIERS.md (+ mirror)
  python3 tools/tool_tiers.py --check    exit 1 if the files are out of date
"""
import json, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TIERS = {1: "wooden", 2: "stone", 3: "iron", 4: "steel"}
# Classes the early-game list or the digging ladder expects, so a missing one shows as a gap.
WANTED = ["axe", "hammer", "knife", "adze", "saw", "spade", "hoe", "pick", "rod", "net", "needle", "torch"]


REC = """## Recommendation (design call, for Dave through Tyler)

Keep the numbers as they are (renumbering would touch digging.json tier_extra, hammer blueprint tiers and saves). Read the tier as the rung inside the class:

| tier | rung | stays / new |
|---|---|---|
| 1 | wooden or first tool | wooden hammer, hoe, spade; stone axe, stone knife (no wooden axe or knife exists, so these are the first rung); torch, rod, net |
| 2 | stone | stone hammer, hoe, spade (exist). No stone pick and no adze (Dave, EARLY_GAME_LIST 15); the saw has no stone rung (planks come from a sawmill, hand saw needs an iron blade) |
| 3 | iron | iron hoe, spade (future), hand saw (exists); iron pick (future) |
| 4 | steel | steel hoe, spade, pick (future) |

Not done on purpose: no copper or bronze rung until Dave asks for one. The stone adze stays retired. The only open early tools are sickle, scythe and rake: nothing in the design says what they do yet, so each waits for a use (plan sent) and then its own build from the reserved block (items 267-299, recipes 170-199), with the name sent to Kathleen first."""


def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def build():
    items = load("data/items/items.json")["items"]
    grid = {}
    for iid, e in items.items():
        c = e.get("tool_class")
        if not c:
            continue
        t = int(e.get("tier", 1))
        cell = grid.setdefault(c, {}).setdefault(t, [])
        cell.append(iid + ("*" if e.get("future") else ""))
    out = ["# Tool tiers", "",
           "Generated by `tools/tool_tiers.py` from `data/items/items.json`. `*` = marked future (no recipe yet).", "",
           "| class | " + " | ".join("%d %s" % (t, n) for t, n in TIERS.items()) + " |",
           "|---|" + "---|" * len(TIERS)]
    for c in sorted(grid):
        row = []
        for t in TIERS:
            row.append(", ".join(sorted(grid[c].get(t, []))) or "-")
        out.append("| %s | %s |" % (c, " | ".join(row)))
    out += ["", "## Gaps", ""]
    for c in WANTED:
        if c not in grid:
            out.append("- **%s**: no item at all" % c)
            continue
        have = sorted(grid[c])
        live = [t for t in have if any(not i.endswith("*") for i in grid[c][t])]
        miss = [TIERS[t] for t in TIERS if t not in live]
        if miss:
            out.append("- **%s**: no live item at %s" % (c, ", ".join(miss)))
    out += ["", REC]
    return "\n".join(out) + "\n"


def main():
    text = build()
    paths = [os.path.join(ROOT, "design/TOOL_TIERS.md"), os.path.join(ROOT, "docs/mirror/design/TOOL_TIERS.md")]
    if "--check" in sys.argv:
        for p in paths:
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
                print("out of date:", p)
                sys.exit(1)
        print("ok")
        return
    for p in paths:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", encoding="utf-8").write(text)
    print(text)


main()
