#!/usr/bin/env python3
"""Writes the balance sheet for Dave from the data files (vitals, exertion, fitness, weights, recipes, items, drops).

Run: python tools/balance_sheet.py [output path]   (default docs/mirror/items/BALANCE.md)
Change the numbers in the data files, never in the sheet or the code.
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "mirror", "items", "BALANCE.md")


def load(name):
    return json.load(open(os.path.join(ROOT, "data/items", name)))


vit, exe, fit, wts, rec, itm, drops = [load(n) for n in ("vitals.json", "exertion.json", "fitness.json", "weights.json", "recipes.json", "items.json", "drops.json")]
items = itm["items"]
body = vit["start_weight_kg"]
flags = []
L = ["# Balance sheet (generated by tools/balance_sheet.py from the data)", "",
     "One table per need, with a plain reading. A game day is one real hour (clock 24:1). Exertion 0 is rest, 1 is hard work all day; walking is about 0.5.", ""]

rest_kcal = vit["rest_kcal_per_kg_day"] * body
L += ["## Food", "", "| Activity | Burn per game day | Full stomach (%d kcal) lasts |" % vit["stomach_cap_kcal"], "|---|---|---|"]
for label, e in (("Resting", 0.0), ("Walking about", 0.5), ("Hard work all day", 1.0)):
    burn = rest_kcal + vit["work_kcal_day"] * e
    hours = vit["stomach_cap_kcal"] / burn * 24
    L.append("| %s | %d kcal | %.0f game hours |" % (label, burn, hours))
    if e == 0.5 and hours < 24:
        flags.append("A full stomach does not last a game day at walking pace (%.0f h): Dave's rule is at least one day." % hours)
L += ["", "Food per item (kcal) and how many make one day of walking (%d kcal):" % (rest_kcal + vit["work_kcal_day"] * 0.5), "", "| Food | kcal each | Items for a day of walking |", "|---|---|---|"]
day_walk = rest_kcal + vit["work_kcal_day"] * 0.5
foods = dict(vit["food"]["by_id"])
for suffix, kcal in vit["food"]["by_suffix"].items():
    foods["(any %s)" % suffix] = kcal
for name, kcal in sorted(foods.items(), key=lambda p: p[1]):
    n = math.ceil(day_walk / kcal)
    L.append("| %s | %d | %d |" % (name.replace("_", " "), kcal, n))
    if n > 40:
        flags.append("%s: %d items to feed one day. Fine as a filler, too weak to live on." % (name, n))
L += ["", "Reading: a day of walking needs about %d kcal, so berries alone (%d each) mean about %d handfuls an hour of play; nuts, roots and a roast are the real meals." % (day_walk, vit["food"]["by_suffix"].get("berries", 90), math.ceil(day_walk / vit["food"]["by_suffix"].get("berries", 90))), ""]

th = vit["thirst"]
L += ["## Water", "", "| Activity | Use per game day | Full body (%d ml) lasts | Mouthfuls (%d ml) per day |" % (th["cap_ml"], th["drink_ml"]), "|---|---|---|---|"]
for label, e in (("Resting", 0.0), ("Walking about", 0.5), ("Hard work all day", 1.0)):
    use = th["rest_ml_day"] + th["work_ml_day"] * e
    hours = th["cap_ml"] / use * 24
    L.append("| %s | %d ml | %.0f game hours | %d |" % (label, use, hours, math.ceil(use / th["drink_ml"])))
    if e == 1.0 and hours < 24:
        flags.append("Water at full work lasts %.0f h, under a game day (Dave's rule: at least one day)." % hours)
L += ["", "Reading: one good drink a day when working normally; hard work needs a drink about every %d game hours." % (th["cap_ml"] / (th["rest_ml_day"] + th["work_ml_day"]) * 24), ""]

mult = lambda f: math.exp(-f * fit["strength"])
L += ["## Exertion and fitness", "",
      "Walking is sustainable; running is not. From the design notes: an unfit (fitness 0) character jogging is winded in about 70 s and sprinting in about 35 s. Recovery is not changed by fitness.", "",
      "| Fitness | Exertion rises at | Jog until winded | Sprint until winded |", "|---|---|---|---|"]
for f in (-10, -5, 0, 5, 10):
    m = mult(f)
    L.append("| %+d | %d%% of normal | %.0f s | %.0f s |" % (f, round(m * 100), 70 / m, 35 / m))
L += ["", "Thresholds: over-exerted at %.2f (pace x%.1f, running on allowed), faint at %.2f, recover below %.2f. Faint lasts %.0f s, waking %.0f s." % (exe["over_on"], exe["over_speed_factor"], exe["faint_at"], exe["over_off"], exe["faint_s"], exe["wake_s"]), ""]

limit = wts["carry_kg_per_body_kg"] * body
free = limit * wts.get("free_ratio", 0.8)
L += ["## Carrying", "", "A %d kg body carries up to %.1f kg; nothing hinders up to %.1f kg (%d%%). In stack terms:" % (body, limit, free, int(wts.get("free_ratio", 0.8) * 100)), "",
      "| Item | kg each | Fits before slowing |", "|---|---|---|"]
default_kg = wts.get("default_kg", 0.1)
for item_id, entry in items.items():
    if entry.get("future"):
        continue
    kg = wts.get("by_id", {}).get(item_id)
    if kg is None:
        kg = next((v for s, v in wts.get("by_suffix", {}).items() if item_id.endswith(s)), default_kg)
    label = entry["name"] + (" (%s)" % item_id if sum(1 for e in items.values() if e["name"] == entry["name"]) > 1 else "")
    L.append("| %s | %.3g | %d |" % (label, kg, int(free / kg) if kg > 0 else 0))
L.append("")

L += ["## Crafting", "", "| Recipe | Needs | Gives | Time | Known at start |", "|---|---|---|---|---|"]
for rid, r in rec["recipes"].items() if isinstance(rec["recipes"], dict) else [(x[0], x[1]) for x in rec["recipes"]]:
    needs = ", ".join("%d %s" % (c, n.replace("_", " ")) for n, c in r["needs"])
    L.append("| %s | %s | %d %s | %.1f s | %s |" % (r["name"], needs, r["gives"][1], r["gives"][0].replace("_", " "), r.get("craft_s", 0), "yes" if r.get("known") else "no"))
    if r.get("craft_s", 0) > 60:
        flags.append("%s takes %.0f s to craft." % (r["name"], r["craft_s"]))
L.append("")

wear = drops["tool_wear"]
L += ["## Tool wear", "", "Full table in TOOL_WEAR.md. Uses before a tool breaks, by kind of work:", "", "| Tool | Durability | Uses |", "|---|---|---|"]
for item_id, entry in items.items():
    if "durability" not in entry or entry.get("future"):
        continue
    per_use = wear["per_use"].get(entry.get("tool_class", ""), {}) or {"use": 1}
    L.append("| %s | %d | %s |" % (entry["name"], entry["durability"], ", ".join("%s %d" % (k, entry["durability"] // max(1, c)) for k, c in per_use.items())))
    if entry["durability"] < 30:
        flags.append("%s breaks after %d wear points. Looks harsh." % (entry["name"], entry["durability"]))

spo, wrm, sick, ene, skl = [load(n) for n in ("spoilage.json", "warmth.json", "sickness.json", "energy.json", "skills.json")]
mult = spo["gentle_mult"]
L += ["", "## Food spoilage (gentle, x%d the strict table)" % mult, "", "A game day is 24 game hours (one real hour). Open air in spring or autumn, in a pack. A woven chest keeps food %.0f%% as fast, a plank chest %.0f%%, the ground %.0f%%; winter x%.1f, summer x%.1f." % (spo["place_mult"]["chest"] * 100, spo["place_mult"]["plank_chest"] * 100, spo["place_mult"]["ground"] * 100, spo["season_mult"]["winter"], spo["season_mult"]["summer"]), "", "| Food | Fresh for (game days) | Real time |", "|---|---|---|"]
seen = {}
for key, hours in list(spo["by_id"].items()) + list(spo["by_suffix"].items()):
    seen[key] = hours * mult / 24.0
for key, days in sorted(seen.items(), key=lambda kv: kv[1]):
    L.append("| %s | %.1f | %.0f min |" % (key.replace("_", " "), days, days * 60))
L += ["", "Stale food feeds less: half fresh gives 75%% of its kcal. Eaten rotten: sick for %.0f game hours (see Sickness)." % sick["duration_h"], ""]
cold_c = wrm["comfort_c"] - (100 - wrm["hurt_at"]) / wrm["gain"]
L += ["## Warmth", "", "Cold starts to hurt health when the body's target warmth drops under %d, which on a still dry day is about %.0f C (comfort %.0f C, %.1f warmth points per degree). Wind chill up to %.0f C, rain or snow on you x%.1f, swimming follows the water (see Swimming); a fire within %.0f m is worth +%.0f C; cover cuts wind to %.0f%%." % (wrm["hurt_at"], cold_c, wrm["comfort_c"], wrm["gain"], wrm["wind_chill_c"], wrm["rain_mult"], wrm["fire_radius_m"], wrm["fire_c"], wrm["covered_wind_share"] * 100), "", "Warmth moves toward its target with a time constant of %.0f game hours falling and %.1f rising; health drains at most %.2f per real second, never below 1." % (wrm["tau_cool_h"], wrm["tau_warm_h"], wrm["hurt_per_s"] * 2), ""]
L += ["## Sickness", "", "Rotten food: sick %.0f game hours (%.0f real minutes), exertion floor %.0f%%, a symptom every %.0f s, %dx faster asleep. Medicine takes off %.0f hours." % (sick["duration_h"], sick["duration_h"] / 24.0 * 60, sick["exertion_floor"] * 100, sick["symptom_every_s"], sick["sleep_mult"], vit["medicines"]["medicine"]["cure_h"]), ""]
sys_ = skl["system"]
L += ["## Skills", "", "Skills run 1 to %d and are trained in steps of %d (an untrained skill stops at %d, each training level adds %d). Each success adds about %.1f practice units x difficulty, with a %.0f s cooldown per skill and a soft cap of %.0f units a game day; a skill costs %.0f units for its first point and %.1f%% more for every point after. Idle skills decay after %.0f game days, halving every %.0f days, never under %.0f%% of the best." % (sys_["max_value"], sys_["step"], sys_["step"], sys_["step"], sys_["gain_units"], sys_["cooldown_s"], sys_["day_cap_units"], sys_["base_cost"], (sys_["growth"] - 1.0) * 100.0, sys_["grace_days"], sys_["half_life_days"], sys_["floor_share"] * 100), "", "| Skill | Parents | Top effect |", "|---|---|---|"]
for sid, sk in skl["skills"].items():
    L.append("| %s | %s | x%.2f |" % (sk["name"], ", ".join(sk.get("parents", {}).keys()) or "root", sk.get("max_factor", 1.0)))
L.append("")

# --- Coins and prices (Radar, build 548) ---
coin = load("coins.json")
tr = coin["trade"]
L += ["## Coins and shop prices", "", "10 copper = 1 bronze, 10 bronze = 1 silver, 10 silver = 1 gold. A stranger pays %.0f%% of an item's value and is paid %.0f%% for it; reputation, charisma and luck move that toward at best x%.2f and %.0f%% (never past). A trader tires of buying the same item: each unit sold lowers its price %.0f points down to %.0f%%, back %.0f points a minute." % (tr["sell_markup"] * 100, tr["buy_discount"] * 100, tr["min_sell"], tr["max_buy"] * 100, tr["demand"]["drop_per_sale"] * 100, tr["demand"]["floor"] * 100, tr["demand"]["recover_per_min"]), "", "| Item | Value (copper) | You pay | You are paid |", "|---|---|---|---|"]
for iid, it in items.items():
    v = it.get("value", 0)
    if v >= 12 and it.get("kind") != "coin" and not it.get("future"):
        L.append("| %s | %d | %d | %d |" % (it["name"], v, round(v * tr["sell_markup"]), max(int(v * tr["buy_discount"]), 1)))
L.append("")

# --- Survival day, all vitals together (Items refill 12) ---
cook = load("cooking.json"); clo = load("items.json")["items"]
def target(temp, wind, ins, rain=0.0, fire=False):
    feels = temp - wind * wrm["wind_chill_c"] + (wrm["fire_c"] if fire else 0)
    stress = max(wrm["comfort_c"] - feels, 0.0)
    if rain > 0.05:
        stress *= 1 + (wrm["rain_mult"] - 1) * min(rain * 2, 1)
    return max(0.0, min(100.0, 100 - stress * wrm["gain"] * (1 - ins)))
def hours_to_hurt(tgt):
    if tgt >= wrm["hurt_at"]:
        return None
    return -wrm["tau_cool_h"] * math.log((wrm["hurt_at"] - tgt) / (100 - tgt))
sets = [("naked", 0.0), ("grass set (skirt, cloak, sandals)", sum(clo[i]["warmth"] for i in ("grass_skirt", "grass_cloak", "fibre_sandals"))), ("hide set (cloak, boots, hood, mittens, leggings)", sum(clo[i]["warmth"] for i in ("hide_cloak", "hide_boots", "hide_hood", "hide_mittens", "hide_leggings")))]
sets = [(n, min(v, wrm["max_insulation"])) for n, v in sets]
temps = [("temperate summer 24 C", 24), ("temperate spring or autumn 10 C", 10), ("temperate winter -4 C", -4), ("arctic winter -23 C", -23)]
L += ["## Survival day, all vitals together", "", "Warmth target in ordinary wind (0.4) on a dry day; the number in brackets is how many game hours until health starts to drain (target under %d), a dash if never. The weather gives a seasonal temperature; warmth adds a day and night swing on top (temperate 5 to 11 C by season, low at 6:30, high at 15:00, smaller in cloud, rain and wind), so dawn in autumn is about 4 C colder than these table values and the afternoon 5 C warmer." % wrm["hurt_at"], "", "| Where | " + " | ".join(n for n, _ in sets) + " |", "|---|" + "---|" * len(sets)]
for name, t in temps:
    cells = []
    for _, ins in sets:
        tg = target(t, 0.4, ins)
        h = hours_to_hurt(tg)
        cells.append("%.0f (%s)" % (tg, "-" if h is None else "%.1f h" % h))
    L.append("| %s | %s |" % (name, " | ".join(cells)))
L += ["", "Swimming (cold follows the water): " + "; ".join("%d C air gives %.0f C water and a warmth target of %.0f naked" % (a, max(wrm["water_base_c"] + wrm["water_follow"] * (a - wrm["water_base_c"]), 1.0), max(0, 100 - max(wrm["water_comfort_c"] - max(wrm["water_base_c"] + wrm["water_follow"] * (a - wrm["water_base_c"]), 1.0), 0) * wrm["water_gain"])) for a in (24, 10, -4)) + ". The body cools with a time constant of %.1f game hours in water (%.0f real minutes), so a cold swim is dangerous within about an hour." % (wrm["tau_water_h"], wrm["tau_water_h"] * 2.5), ""]
cx = [(ck, sp) for ck, sp in (("roast forage", spo["by_id"]["roast_forage"]), ("roast meat", spo["by_id"]["roast_meat"]), ("raw meat", spo["by_id"]["raw_meat"]))]
L += ["Cooking: a roast keeps %.1f times what the raw item had left, up to its own shelf life; roast forage up to %.0f game days, roast meat %.0f, raw meat %.0f. A hot meal adds %d warmth points when eaten (roast forage), tea %d. Raw meat, fiddleheads and beans make you sick for 12 to 24 hours, acorns and wild mushrooms for 6." % (cook["cooked_life_mult"], spo["by_id"]["roast_forage"] * mult / 24, spo["by_id"]["roast_meat"] * mult / 24, spo["by_id"]["raw_meat"] * mult / 24, cook["warms"]["roast_forage"], cook["warms"]["herbal_tea"]), ""]
L += ["A game day, put together: food lasts 24 game hours of walking, water 36, energy %s (see Energy); cold is the only vital that can hurt a well-fed, rested character, and only in winter or in water without clothes. Sickness (6 to 24 hours at exertion 0.5) costs food and water but never health beyond what hunger already allows." % ("3 game days awake, then sleep"), ""]

# --- Fishing and stations ---
fsh = load("fishing.json"); strc = load("structures.json")["structures"]; rcp = load("recipes.json")["recipes"]
base = fsh["base_chance"]
L += ["## Fishing", "", "A cast waits %.0f to %.0f s, then a bite lasts %.0f s. Chance of a bite on a cast (fresh pond, novice, no bait): %.0f%% base; dawn or dusk x1.3, midday x0.7, light rain x%.1f, storm x%.1f, cold water x%.1f, bait x%.1f, ice hole x%.1f." % (fsh["wait_s"][0], fsh["wait_s"][1], fsh["window_s"], base * 100, fsh["rain_mult"], fsh["storm_mult"], fsh["cold_mult"], fsh["bait_mult"], fsh["ice"]["ice_mult"]), ""]
avg_wait = (fsh["wait_s"][0] + fsh["wait_s"][1]) / 2 + 3
L += ["A cast takes about %.0f s of waiting. At %.0f%% that would be %.0f bites an hour without any limit, so the hidden stock is what really paces fishing: a cell holds only %d to %d fish and gets one back per game day (one real hour), so a spot gives about %d to %d fish at first and then roughly one an hour, however good the player is." % (avg_wait, base * 130, 3600 / avg_wait * base * 1.3, fsh["stock_base"], fsh["stock_base"] + fsh["stock_extra"], fsh["stock_base"], fsh["stock_base"] + fsh["stock_extra"]), "Spear: %.0f%% for a novice, at most %.0f%%, depth %.1f m or less, a jab every %.1f s." % (fsh["spear"]["base_chance"] * 100, fsh["spear"]["max_chance"] * 100, fsh["spear"]["max_depth_m"], fsh["spear"]["cooldown_s"]), "A trout feeds %d kcal raw, %d roasted (%.1f of a walking day's 2400 kcal)." % (load("vitals.json")["food"]["by_id"]["trout"], load("vitals.json")["food"]["by_id"]["roast_fish"], load("vitals.json")["food"]["by_id"]["roast_fish"] / 2400.0), ""]
L += ["## Crafting stations", "", "A station recipe needs a placed station within reach (camp bench %.0f m) and its level: 1, plus one for each add-on kind (tool rack, vice) within %.0f m." % (strc["workbench"]["reach_m"], strc["workbench"]["addon_reach_m"]), "", "| Recipe | Station | Level | Needs |", "|---|---|---|---|"]
for rid, rr in rcp.items():
    if rr.get("station"):
        L.append("| %s | %s | %d | %s |" % (rr["name"], rr["station"].replace("_", " "), rr.get("station_level", 1), ", ".join("%d %s" % (n[1], n[0]) for n in rr["needs"])))
L += [""]
L += ["Station tiers (Dave 2026-10-21, all placeable): " + "; ".join("%s %s (workbench %d%s)" % (v.get("tier", ""), k.replace("_", " "), v["station_level"], ", forge %d" % v["also"]["forge"] if v.get("also") else "") for k, v in strc.items() if v.get("tier")) + ".", ""]

# --- Skill web hours (tools/skills_sim.py, Tyler's curve; the web is not built yet) ---
import importlib.util
spec = importlib.util.spec_from_file_location("skills_sim", os.path.join(os.path.dirname(os.path.abspath(__file__)), "skills_sim.py"))
sim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sim)
class SimArgs:
    day_cap = 300.0; base = 40.0; growth = 1.045; gen = 1.5; cap_step = 25; train_speed = 1.2
tabs = [sim.simulate(d, SimArgs) for d in (0, 1, 2)]
L += ["## Skills web: hours of play to reach each value (design, not built)", "", "From tools/skills_sim.py: practice cost of the next point = 40 x 1.045^(n-1) x 1.5 per generation, 300 practice units a game day (a real hour) at most, untrained cap 25, +25 per training level (a teacher is assumed found at each cap; training gains x1.2). Real hours of play for one skill. Depth 0 is a foundation like Athleticism, depth 1 a skill under it, depth 2 a subskill.", "", "| Value | Depth 0 | Depth 1 | Depth 2 |", "|---|---|---|---|"]
for v in (15, 25, 40, 50, 65, 75, 90, 100):
    L.append("| %d | %.0f h | %.0f h | %.0f h |" % (v, tabs[0][v][0], tabs[1][v][0], tabs[2][v][0]))
L += [""]
L += ["", "## What looks off", ""]
L += ["- " + f for f in flags] or ["Nothing in these tables trips the checks (a day of food, a day of water, craft times under a minute, tools of 30+ uses)."]
open(out_path, "w").write("\n".join(L) + "\n")
print("wrote", out_path, "flags:", len(flags))
