#!/usr/bin/env python3
"""Master item list (Sal goal 2): every live item with its number, kind, source, cost, inspect text, use, look, weight and value, and a count of
the empty cells. Writes design/ITEM_MASTER_LIST.md (and the mirror) and prints the gaps.   python3 tools/item_master_list.py [--check]"""
import json, re, sys, glob, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def load(name):
    return json.load(open(os.path.join(root, "data/items", name)))

items = load("items.json")["items"]
recipes = load("recipes.json")["recipes"]
structures = load("structures.json")["structures"]
looks = load("looks.json").get("items", {})
weights = load("weights.json").get("by_id", {})
uses_note = load("item_uses.json")["uses"]
CODE_LOOKS = ("stick", "log", "driftwood", "plant_fibre", "firewood")   # drawn by inventory_view.gd as a log shape
texts = {}
for path in glob.glob(os.path.join(root, "data/items/*.json")):
    base = os.path.basename(path)
    if base not in ("items.json", "recipes.json", "weights.json", "looks.json", "structures.json", "item_uses.json"):
        texts[base] = open(path).read()
text_all = "\n".join(texts.values())

made_by, used_in = {}, {}
for rid, r in recipes.items():
    if r.get("retired"):
        continue
    gives = r["gives"][0]
    made_by.setdefault(gives, []).append(rid)
    for need in r["needs"]:
        used_in.setdefault(need[0], []).append(rid)
struct_items = {}
for kind, s in structures.items():
    for field in ("kit", "item"):
        if s.get(field):
            struct_items.setdefault(s[field], []).append(kind)

def use_of(item):
    kind = item.get("kind")
    if item.get("tool_class"):
        return "tool: %s tier %s" % (item["tool_class"], item.get("tier", 1))
    if kind == "food":
        return "food"
    if item["id"] in uses_note:
        return uses_note[item["id"]]
    if kind in ("placeable", "structure"):
        return "placed: " + ", ".join(struct_items.get(item["id"], [])) if struct_items.get(item["id"]) else ""
    if kind == "clothing" or kind == "gear":
        return "worn: slot %s" % item.get("slot", "?")
    if kind == "weapon":
        return "weapon: %s" % item.get("weapon_class", "?")
    if kind == "container":
        return "container"
    if kind == "coin":
        return "coin"
    if kind == "medicine":
        return "medicine"
    if item["id"] in used_in:
        return "ingredient of " + ", ".join(used_in[item["id"]][:3])
    return uses_note.get(item["id"], "")

rows, gaps = [], {}
for iid, item in items.items():
    if item.get("retired"):
        continue
    item = dict(item, id=iid)
    source = ", ".join("recipe " + r for r in made_by.get(iid, []))
    if not source and re.search(r'"%s"' % re.escape(iid), text_all):
        source = "world (gathered, dropped, caught or cooked: see data/items)"
    if not source and iid in struct_items:
        source = "placed piece"
    cost = ""
    if iid in made_by:
        r = recipes[made_by[iid][0]]
        cost = ", ".join("%d %s" % (n[1], n[0]) for n in r["needs"])
    look = "looks.json" if iid in looks or iid in CODE_LOOKS or iid.startswith("log_") else ("pile" if "pile" in item else ("structure look" if iid in struct_items else ""))
    weight = weights.get(iid)
    row = {"number": item["number"], "id": iid, "name": item["name"], "kind": item["kind"], "source": source, "cost": cost,
           "inspect": item.get("description", ""), "use": use_of(item), "look": look,
           "status": "future" if item.get("future") else "live", "weight": "" if weight is None else str(weight), "value": str(item.get("value", ""))}
    rows.append(row)
    for cell in ("source", "inspect", "use", "look", "value"):
        if not row[cell] and not (cell == "value" and item["kind"] == "structure") and not (cell == "source" and item.get("future")):
            gaps.setdefault(cell, []).append(iid)

gathered = json.load(open(os.path.join(root, "data/items/gathered.json")))["items"]
gathered_gaps = [gid for gid, g in gathered.items() if not g.get("description")]
rows.sort(key=lambda r: r["number"])
out = ["# Master item list (generated by tools/item_master_list.py; do not edit by hand)",
       "%d items (%d live, %d future). Empty cells: %s." % (len(rows), sum(1 for r in rows if r["status"] == "live"), sum(1 for r in rows if r["status"] == "future"), ", ".join("%s %d" % (k, len(v)) for k, v in sorted(gaps.items())) or "none"), "",
       "| # | id | name | kind | status | source | cost | use | look | kg | value |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    out.append("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (r["number"], r["id"], r["name"], r["kind"], r["status"], r["source"] or ("not yet" if r["status"] == "future" else "**?**"), r["cost"], r["use"] or "**?**", r["look"] or "**?**", r["weight"] or "default", r["value"] or "**?**"))
out.append("")
out.append("## Gathered items (data/items/gathered.json, one plain material per flora yield): %d, %d without an inspect text" % (len(gathered), len(gathered_gaps)))
out.append("These are made by tools/gen_gathered_items.py and carry no description yet (next step of Sal goal 2): " + ", ".join(gathered_gaps))
out.append("")
for cell, ids in sorted(gaps.items()):
    out.append("## Empty %s (%d)\n%s\n" % (cell, len(ids), ", ".join(ids)))
text = "\n".join(out)
if "--check" not in sys.argv:
    for path in ("design/ITEM_MASTER_LIST.md", "docs/mirror/design/ITEM_MASTER_LIST.md"):
        os.makedirs(os.path.dirname(os.path.join(root, path)), exist_ok=True)
        open(os.path.join(root, path), "w").write(text)
print("%d items; empty cells: %s; gathered items without an inspect text: %d of %d" % (len(rows), {k: len(v) for k, v in gaps.items()}, len(gathered_gaps), len(gathered)))
if "--check" in sys.argv and gaps:
    sys.exit(1)
