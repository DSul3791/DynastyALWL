#!/usr/bin/env python3
"""Master item list with gaps (goal 2): python3 tools/item_master.py [out.md].
Per item: kind, value, made by (recipe), used in (recipes), future flag, and a gap list."""
import json, sys, collections

items = [dict(v, id=k) for k, v in json.load(open("data/items/items.json"))["items"].items()]
recipes = json.load(open("data/items/recipes.json"))["recipes"]
by_number = {i["number"]: i for i in items}
by_name = {}
for i in items:
    by_name.setdefault(i.get("id", i["name"]), i)

def item_of(ref):
    return by_number.get(ref) if isinstance(ref, int) else by_name.get(ref)

made = collections.defaultdict(list)
used = collections.defaultdict(list)
for rid, r in recipes.items():
    g = r.get("gives")
    if g:
        made[g[0]].append(rid)
    for n in r.get("needs", []):
        used[n[0]].append(rid)

def key(i):
    return i["id"]

rows = []
gaps = collections.Counter()
for i in items:
    k = key(i)
    ids = {k, i["name"], str(i["number"])}
    m = sorted({r for x in ids for r in made.get(x, [])})
    u = sorted({r for x in ids for r in used.get(x, [])})
    gap = []
    if i.get("retired"):
        continue
    if not m and i["kind"] in ("tool", "clothing", "structure", "placeable", "weapon", "container", "gear") and not i.get("future"):
        gap.append("no recipe")
    if i.get("value") is None and i["kind"] != "structure":   # placed structures are not traded; their kits carry the price
        gap.append("no value")
    if i["kind"] == "material" and not u and not i.get("future"):
        gap.append("not used")
    if i.get("future"):
        gap.append("future")
    for g in gap:
        gaps[g] += 1
    rows.append((i["kind"], i["number"], i["name"], i.get("value", ""), len(m), len(u), ", ".join(gap)))

out = ["# Item master list (generated by tools/item_master.py)", "", "Structures and placeables are built from blueprints (structures.json costs), so their 'no recipe' is expected; 'future' means the item exists in data but is not yet reachable.", "", "Total items: %d. Gaps: %s" % (len(rows), ", ".join("%s %d" % kv for kv in gaps.most_common())), ""]
for kind in sorted({r[0] for r in rows}):
    out.append("## %s" % kind)
    out.append("| # | item | value | recipes making it | recipes using it | gaps |")
    out.append("|---|---|---|---|---|---|")
    for r in sorted(x for x in rows if x[0] == kind):
        out.append("| %d | %s | %s | %d | %d | %s |" % r[1:])
    out.append("")
text = "\n".join(out)
if len(sys.argv) > 1:
    open(sys.argv[1], "w").write(text)
else:
    print(text)
