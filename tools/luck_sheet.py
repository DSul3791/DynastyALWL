#!/usr/bin/env python3
"""Writes the luck numbers sheet for Dave from the data (luck.json strength, drops.json yields and chances, boulders.json).

Run: python3 tools/luck_sheet.py [output path]   (default /mnt/project-files/items/LUCK_NUMBERS.md)
Uses the same maths as src/shared/luck.gd. Change the strength in data/items/luck.json, never here.
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files/items/LUCK_NUMBERS.md"


def load(name):
    return json.load(open(os.path.join(ROOT, "data/items", name)))


luck, drops, boulders = load("luck.json"), load("drops.json"), load("boulders.json")
S = luck["strength"]
LEVELS = (-10, -5, 0, 5, 10)


def p_chance(p, lk):
    """Chance of success: u**exp(lk*S) < p  <=>  u < p**exp(-lk*S)."""
    return p ** math.exp(-lk * S) if 0 < p < 1 else p


def mean_amount(lo, hi, lk, n=20000):
    total = 0
    for i in range(n):
        u = (i + 0.5) / n
        total += min(hi, lo + int(u ** math.exp(-lk * S) * (hi - lo + 1)))
    return total / n


L = ["# Luck numbers (generated by tools/luck_sheet.py from the data)", "",
     "Luck is a whole number from -10 to +10, rolled once at character creation (2 dice of 5 faces, so most people land within about 3 of zero), never trained. "
     "Strength per point is %s (data/items/luck.json). Set it to 0 and luck does nothing. Tell me if +10 is too strong or too weak and I change that one number." % S, ""]

L += ["## Chance rolls", "", "How a chance that is 10, 30, 50 or 90 percent for a neutral character changes:", "",
      "| Luck | 10% becomes | 30% becomes | 50% becomes | 90% becomes |", "|---|---|---|---|---|"]
for lk in LEVELS:
    L.append("| %+d | %.1f%% | %.1f%% | %.1f%% | %.1f%% |" % ((lk,) + tuple(100 * p_chance(p, lk) for p in (0.1, 0.3, 0.5, 0.9))))
L.append("")

L += ["## Gather yield (average items per pick)", "", "| Plant | Yield range | " + " | ".join("Luck %+d" % lk for lk in LEVELS) + " |", "|---|---|" + "---|" * len(LEVELS)]
for species, entry in drops["by_species"].items():
    item, lo, hi = entry[0]
    L.append("| %s (%s) | %d to %d | " % (species.replace("_", " "), item.replace("_", " "), lo, hi) + " | ".join("%.2f" % mean_amount(lo, hi, lk) for lk in LEVELS) + " |")
shrub = drops["by_kind"]["shrub"][0]
L.append("| shrub (%s) | %d to %d | " % (shrub[0], shrub[1], shrub[2]) + " | ".join("%.2f" % mean_amount(shrub[1], shrub[2], lk) for lk in LEVELS) + " |")
L.append("")

tr = drops["trunk"]
L += ["## Felled tree drops", "", "Chances that a blow on a felled trunk also gives something (neutral value, then by luck):", "",
      "| Drop | Neutral | " + " | ".join("Luck %+d" % lk for lk in (-10, 10)) + " |", "|---|---|---|---|"]
for label, key in (("Bark", "bark_chance"), ("Seed or nut", "seed_chance")):
    p = tr[key]
    L.append("| %s | %.0f%% | %.1f%% | %.1f%% |" % (label, 100 * p, 100 * p_chance(p, -10), 100 * p_chance(p, 10)))
for label, key in (("Branch sticks", "branch"), ("Roots", "roots")):
    entry = tr[key][0] if key == "branch" else tr[key]
    item, lo, hi = entry
    L.append("| %s (%d to %d each) | %.2f average | %.2f | %.2f |" % (label, lo, hi, mean_amount(lo, hi, 0), mean_amount(lo, hi, -10), mean_amount(lo, hi, 10)))
L.append("")

p = boulders["luck_extra"]
L += ["## Boulders", "", "Each blow that has another stone left gives a second stone with %.0f%% chance for a neutral character: %.1f%% at luck -10, %.1f%% at +10. "
      "On a 1 m boulder (about 4,600 stones) that is a few hundred extra stones across the whole job." % (100 * p, 100 * p_chance(p, -10), 100 * p_chance(p, 10)), ""]

L += ["## Tool wear", "", "Luck does not touch tool wear yet; every use costs its fixed amount (TOOL_WEAR.md). If you want lucky people to wear tools slower, say so and it becomes one more fate roll.", ""]
L += ["## The counter", "", "The server counts every fate roll by kind (`fate_counts` in server_items.gd), so we can read what luck actually touched in a play session. "
      "Today the only fate kind is the boulder bonus stone; chance and amount rolls go through the same function but are not counted by kind.", ""]
open(out_path, "w").write("\n".join(L) + "\n")
print("wrote", out_path)
