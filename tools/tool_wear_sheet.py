#!/usr/bin/env python3
"""Writes the tool wear and repair sheet for Dave from the data (items.json durability and repair, drops.json tool_wear).

Run: python3 tools/tool_wear_sheet.py [output path]   (default /mnt/project-files/items/TOOL_WEAR.md)
Change the numbers in the data files, never in the sheet or the code.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files/items/TOOL_WEAR.md"
items = json.load(open(os.path.join(ROOT, "data/items/items.json")))["items"]
wear = json.load(open(os.path.join(ROOT, "data/items/drops.json")))["tool_wear"]
trade = json.load(open(os.path.join(ROOT, "data/items/coins.json")))["trade"]
SECONDS_PER_USE = 2.0   # assumption: one use about every two seconds of steady work
rows = []
lines = ["# Tool wear and repair (generated by tools/tool_wear_sheet.py from the data)", "",
         "Wear is counted in uses; a tool breaks at its durability. Repair needs the materials listed and gives back %d%% of the durability." % int(wear["repair_restores"] * 100), "",
         "| Tool | Class | Durability (wear points) | Uses before it breaks, by kind of work | Minutes of steady work | Repair materials | Where | Smith, fully worn (stranger) |", "|---|---|---|---|---|---|---|---|"]

for item_id, entry in items.items():
    if "durability" not in entry:
        continue

    klass = entry.get("tool_class", "")
    per_use = wear["per_use"].get(klass, {})
    kinds = per_use if per_use else {"use": 1}
    uses = ", ".join("%s %d" % (kind, entry["durability"] // max(1, cost)) for kind, cost in kinds.items())
    repair = ", ".join("%d %s" % (count, name.replace("_", " ")) for name, count in entry.get("repair", []))
    where = ("a %s nearby" % entry["repair_station"]) if entry.get("repair_station") else "by hand"
    smith = int(-(-entry.get("value", 0) * trade["repair"]["rate"] * trade["sell_markup"] // 1)) if entry.get("value", 0) > 0 else 0
    lines.append("| %s | %s | %d | %s | %.1f | %s | %s | %d copper |" % (entry["name"], klass or "weapon", entry["durability"], uses, entry["durability"] * SECONDS_PER_USE / 60.0, repair, where, smith))

lines += ["", "A smith (shops.json \"repairs\": true) mends any worn or broken tool as new for value x %.2f x the share worn x the pay multiple. Minutes assume one use every %d seconds." % (trade["repair"]["rate"], SECONDS_PER_USE), "", "Kinds of work: gather (a plant yield that needs the tool), rock (stone from an outcrop), tree (one blow on a standing tree), trunk (one blow on a felled trunk), split (one log at the chopping block). Weapons wear per throw or jab (placeholder: 1).", ""]
os.makedirs(os.path.dirname(out_path), exist_ok=True)
open(out_path, "w").write("\n".join(lines))
print("wrote", out_path)
