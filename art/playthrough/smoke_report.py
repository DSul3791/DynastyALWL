#!/usr/bin/env python3
"""Smoke test report: reads art/playthrough/smoke/logs/*.log and writes SMOKE_TEST.md (every distinct error and warning, counted, with an owner and a severity).
    python art/playthrough/smoke_report.py"""
import glob
import os
import re
from collections import OrderedDict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LOGS = os.path.join(ROOT, "art", "playthrough", "smoke", "logs")

# (pattern in the message or the next 'at:' line, owner)
OWNERS = [
    (r"character|creator|body_generator|avatar|page_style|hair|clip_converter", "Sonny (character)"),
    (r"water|sea|river|drain|shore", "Sonny (water)"),
    (r"flora|tree_builder|tree_impostor|fall_growth|grass|plant|fern|foliage", "flora session (Kathleen for looks)"),
    (r"basic_look|building_look|held_item|piece_look|look_table|structure_look|fire|campfire", "Kathleen (looks)"),
    (r"voxel|terrain|tile|chunk|block", "Tyler (terrain)"),
    (r"server_items|inventory|recipe|craft|item_table", "Tyler / Sal (items)"),
    (r"animal|wolf|flock|herd", "Tyler (animals)"),
    (r"sound|audio|ambient|voice|speech", "Sonny / Tyler (sound)"),
    (r"shader|material|texture|mesh|rendering|vulkan|d3d", "Kathleen (rendering)"),
    (r"npc|dialogue|trade|town", "Sonny (NPCs)"),
]
HIGH = re.compile(r"SCRIPT ERROR|Parse Error|Failed to load|Cannot open|Invalid (call|access|assignment)|Condition .* is true|Crash report|Segmentation|SHADER ERROR|shader.*error|Identifier not found|Nonexistent function|Attempt to call|Out of bounds", re.I)
KNOWN_EXIT = re.compile(r"ObjectDB instances leaked|resources still in use at exit|VoxelMemoryPool: \d+ memory blocks are still used", re.I)


def normalize(line: str) -> str:
    line = re.sub(r"\d{4}-\d\d-\d\dT[\d:]+", "T", line)
    line = re.sub(r"\[\+[\d.]+ s\]", "", line)
    line = re.sub(r"-?\d+\.\d+", "N", line)
    line = re.sub(r"\b\d+\b", "N", line)
    return line.strip()[:240]


def owner_of(text: str) -> str:
    for pattern, who in OWNERS:
        if re.search(pattern, text, re.I):
            return who
    return "unassigned (moderator)"


rows = OrderedDict()
summary = []

for path in sorted(glob.glob(os.path.join(LOGS, "*.log")) + glob.glob(os.path.join(LOGS, "*.out"))):
    name = os.path.basename(path)
    text = open(path, encoding="utf8", errors="replace").read()
    lines = text.splitlines()
    problems = 0
    crash = "Crash report written" in text or "Segmentation fault" in text or "SMOKE: TIMEOUT" in text

    for n, line in enumerate(lines):
        if not re.match(r"\s*(SCRIPT ERROR|ERROR|WARNING|USER ERROR|USER WARNING|Parse Error)", line) and not HIGH.search(line):
            continue

        if KNOWN_EXIT.search(line):
            continue

        context = line + " " + (lines[n + 1] if n + 1 < len(lines) and re.match(r"\s+at:", lines[n + 1]) else "")
        key = normalize(context)
        sev = "HIGH" if (HIGH.search(context) or line.lstrip().startswith(("SCRIPT ERROR", "Parse Error"))) else ("LOW" if line.lstrip().startswith(("WARNING", "USER WARNING")) else "MEDIUM")
        row = rows.setdefault(key, {"count": 0, "sev": sev, "logs": set(), "owner": owner_of(context), "sample": context.strip()[:260]})
        row["count"] += 1
        row["logs"].add(name)
        problems += 1

    summary.append((name, len(lines), problems, crash))

out = ["# SMOKE_TEST: the daily branch head, run through the real server and client", "",
       "Generated by `art/playthrough/smoke_report.py` from `art/playthrough/smoke/logs/`. Run: `bash art/playthrough/smoke_test.sh` (character select and creator in a real window, a windowed client walking for 3 minutes against a real server, then one headless client per self-test flag: arrival, gather, plantpick, chop, fire, cook, leanto, sleep, spear, creatures, snare, chest, quickkeys, eat, placed, walk).", "",
       "## Runs", "", "| log | lines | errors and warnings | crash or timeout |", "|---|---|---|---|"]

for name, n, problems, crash in summary:
    out.append("| %s | %d | %d | %s |" % (name, n, problems, "**YES**" if crash else "no"))

order = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
out += ["", "## Distinct errors and warnings (HIGH first, then by count)", "", "| sev | count | message | seen in | owner |", "|---|---|---|---|---|"]

for key, row in sorted(rows.items(), key=lambda kv: (order[kv[1]["sev"]], -kv[1]["count"])):
    out.append("| %s | %d | `%s` | %s | %s |" % (row["sev"], row["count"], row["sample"].replace("|", "/").replace("`", "'"), ", ".join(sorted(row["logs"]))[:80], row["owner"]))

if not rows:
    out.append("| - | 0 | no errors or warnings found | | |")

notes_path = os.path.join(ROOT, "art", "playthrough", "smoke", "notes.md")
if os.path.exists(notes_path):
    out += ["", "## Notes (hand-written, kept in art/playthrough/smoke/notes.md)", "", open(notes_path, encoding="utf8").read().rstrip()]

open(os.path.join(ROOT, "SMOKE_TEST.md"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("SMOKE_TEST.md:", len(rows), "distinct messages;", sum(1 for r in rows.values() if r["sev"] == "HIGH"), "HIGH")
