#!/usr/bin/env python3
"""Playthrough helper: turns art/playthrough/audit.json plus the data tables into PLAYTHROUGH_CHAPTERS.md, the tier-by-tier part of the guide.
Every row is derived from data (recipes.json, structures.json, blueprints.json, items.json, looks.json), so the numbers cannot drift from the game.
Run after audit_playthrough.py:  python art/playthrough/make_chapters.py"""
import json
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def load(p):
    return json.load(open(os.path.join(ROOT, p), encoding="utf8"))


audit = load("art/playthrough/audit.json")
recipes = {k: v for k, v in load("data/items/recipes.json")["recipes"].items() if not v.get("retired")}
items = {**load("data/items/items.json")["items"], **load("data/items/gathered.json")["items"]}
blue = {k: v for k, v in load("data/items/blueprints.json")["blueprints"].items() if not v.get("retired")}
structs = load("data/items/structures.json")["structures"]
irow = {r["id"]: r for r in audit["items"]}
rrow = {r["id"]: r for r in audit["recipes"]}
try:
    shelf = {k: "showroom/sr_" + v + ".jpg" for k, v in load("art/playthrough/showroom/rows.json").items()}
except Exception:
    shelf = {}


def name(i):
    return items.get(i, {}).get("name", i)


def need_text(r):
    parts = ["%d x %s" % (n, i) for i, n in r["needs"]]
    keeps = ["%s (kept)" % i for i, n in r.get("keeps", [])]
    return ", ".join(parts + keeps)


def srcs(i):
    s = irow.get(i, {}).get("sources", [])
    short = [x for x in s if not x.startswith("recipe:")][:2]
    rec = [x for x in s if x.startswith("recipe:")]
    return "; ".join(short + rec[:1]) if s else "NO SOURCE"


def status(rid):
    r = rrow[rid]
    g = irow.get(r["gives"], {})
    look = g.get("look", "")
    if r["blocked_by"]:
        bits = r["blocked_by"]
        tag = "FUTURE (flagged by design)" if r["future"] else "BLOCKER"
        if any("no source" in b for b in bits):
            return "MISSING ITEM (%s): %s" % (tag, "; ".join(bits))
        return "MECHANIC BROKEN or not learnable (%s): %s" % (tag, "; ".join(bits))
    if look and not look.startswith("ok") and look != "override look":
        return "LOOKS WRONG: " + look
    return "PASS" + (" (wave %s)" % r["wave_now"] if r["wave_now"] else "")


CHAPTERS = [
    ("2", "Stone age by hand: twine, axe, knife, spear", lambda r: not r["station"] and r["category"] in ("Materials", "Tools", "Weapons")),
    ("3", "Fire, food, drink and medicine by hand", lambda r: not r["station"] and r["category"] in ("Fire and cooking", "Food and drink", "Medicine")),
    ("4", "Shelter, clothing, containers and furniture by hand", lambda r: not r["station"] and r["category"] in ("Shelter and building", "Containers and furniture", "Clothing", "Workshops and stations")),
    ("5", "Cooking stations: campfire, pot, clay hearth, oven", lambda r: r["station"] in ("campfire", "campfire_pot", "clay_hearth", "oven")),
    ("6", "Workbench tier 1: hammer, bow, thatch house pieces", lambda r: r["station"] == "workbench" and int(r["station_level"]) == 1),
    ("7", "Bigger benches (log workbench, stone forge, blacksmithy)", lambda r: r["station"] == "workbench" and int(r["station_level"]) >= 2),
    ("8", "Wood tier: saw mill and woodworking table", lambda r: r["station"] in ("saw_mill", "woodworking_table")),
    ("9", "Forge and metal: bronze, iron, steel", lambda r: r["station"] == "forge"),
]

INTRO = {
    "2": "The first hour. Hands only, no station. Every recipe here is open (known:true) unless the table says otherwise.",
    "3": "Fire is lit from a kit (campfire) and cooked at with E; these are the hand recipes for food and medicine.",
    "4": "Roofs, beds, boxes, packs and clothes. Kits are placed with left click; lean-to, bed, chest, chopping block need no station.",
    "5": "Recipes cooked AT a placed fire or hearth. campfire = any lit fire; campfire_pot needs the pot kit hung on a fire; clay_hearth level 2 and oven level 3 are built from the hammer.",
    "6": "Recipes made near a placed workbench (12 sticks + 3 twine). Add-ons (tool rack, vice) raise its level.",
    "7": "Higher benches are placed from the hammer with materials (blueprints.json): stone forge gives workbench level 3 and forge 1, blacksmithy workbench 4 and forge 2.",
    "8": "Boards and beams. A saw mill (placed from the hammer) turns one log into lumber; a woodworking table makes fine boards.",
    "9": "Smelting and smithing at a forge. Needs ores, coal and ingots.",
}

out = []
out.append("# PLAYTHROUGH_CHAPTERS: the guide by tier\n")
out.append("Generated by `art/playthrough/make_chapters.py` from the data tables and `art/playthrough/audit.json` (run `audit_playthrough.py` first). Part 1 (chapter 1, the first day) is in `PLAYTHROUGH_GUIDE.md`. Statuses: **PASS** (makeable today and looks right), **LOOKS WRONG**, **MISSING ITEM** (an ingredient has no source anywhere), **MECHANIC BROKEN** (known:false so nobody can craft it, or a station that cannot be built). `FUTURE` = the product is flagged `future:true` in items.json (by design not yet in play), `BLOCKER` = not flagged, so a real gap. Pictures: `art/playthrough/showroom/<row>.jpg` (every item, 10 per row, with name tags).\n")

# chapter 1: the raw world
out.append("\n## Chapter 1b: what the world gives (every natural source)\n")
out.append("Natural sources found in `drops.json`, `digging.json`, `carcass.json`, `fishing.json`, the log chain and NPC data. `look` is the item's look status.\n")
out.append("| item | kind | sources | obtainable | look | picture |\n|---|---|---|---|---|---|")
natural = [r for r in audit["items"] if any(not s.startswith("recipe:") for s in r["sources"])]
for r in natural:
    out.append("| %s | %s | %s | %s | %s | %s |" % (r["id"], r["kind"], "; ".join(x for x in r["sources"] if not x.startswith("recipe:"))[:90], r["obtainable"], r["look"], shelf.get(r["id"], "")))

score = []
for num, title, pick in CHAPTERS:
    rs = sorted([r for r in audit["recipes"] if pick(r)], key=lambda r: ((r["wave_potential"] or 99), r["number"]))
    out.append("\n## Chapter %s: %s\n" % (num, title))
    out.append(INTRO.get(num, "") + "\n")
    out.append("| step | recipe # | make | needs (and where each comes from) | station | known | status | picture row |\n|---|---|---|---|---|---|---|---|")
    for n, r in enumerate(rs, 1):
        rec = recipes[r["id"]]
        needs = "; ".join("%d x %s [%s]" % (c, i, srcs(i)[:60]) for i, c in rec["needs"])
        keeps = "; ".join("%s kept [%s]" % (i, srcs(i)[:40]) for i, c in rec.get("keeps", []))
        out.append("| %d | %d | %s -> %d x %s | %s | %s | %s | %s | %s |" % (
            n, r["number"], r["id"], rec["gives"][1], r["gives"], needs + ((" | keeps: " + keeps) if keeps else ""), (r["station"] + " L" + str(r["station_level"])) if r["station"] else "hands",
            "yes" if r["known"] else "NO", status(r["id"]), shelf.get(r["gives"], "")))
    c = {"PASS": 0, "LOOKS WRONG": 0, "BLOCKER": 0, "FUTURE": 0}
    for r in rs:
        st = status(r["id"])
        if st.startswith("PASS"): c["PASS"] += 1
        elif st.startswith("LOOKS"): c["LOOKS WRONG"] += 1
        elif "(FUTURE" in st: c["FUTURE"] += 1
        else: c["BLOCKER"] += 1
    score.append((num, title, len(rs), c))
    # checklist
    out.append("\nChecklist for chapter %s:\n" % num)
    for r in rs:
        st = status(r["id"])
        out.append("- [%s] %s: %s" % ("x" if st.startswith("PASS") else " ", r["id"], st))

# stations and structures
out.append("\n## Chapter 10: every structure, bench and building piece\n")
out.append("How each placeable is obtained (kit recipe or hammer blueprint with its cost), its size and cap, the station level it gives, and problems found by the audit. Pictures: run `rig.sh --pieces <name>` (see PLAYTHROUGH_FINDINGS.md section 5).\n")
out.append("| structure | obtained by | footprint (m) | cap/chunk | gives station | add-on of | built today | built if all known | problems |\n|---|---|---|---|---|---|---|---|---|")
for s in audit["structures"]:
    sp = structs[s["id"]]
    how = []
    kit = sp.get("kit", "")
    kr = [k for k, v in recipes.items() if v["gives"][0] == kit]
    if kr:
        how.append("recipe " + kr[0] + ": " + need_text(recipes[kr[0]]))
    for b in blue.values():
        if b["structure"] == s["id"]:
            how.append("hammer blueprint: " + ", ".join("%d x %s" % (c, i) for i, c in b["cost"]) + (" at " + b["station"] if b.get("station") else ""))
    if not how:
        how.append("(none: placed by game or admin)")
    st = ("%s L%s" % (s["station"], s["station_level"])) if s["station"] else ""
    if s["also"]:
        st += " + " + ", ".join("%s L%s" % (k, v) for k, v in s["also"].items())
    out.append("| %s | %s | %sx%s | %s | %s | %s | %s | %s | %s |" % (s["id"], " ; ".join(how)[:140], s["footprint"][0], s["footprint"][1], s["cap"], st, s["addon_of"], s["built_wave_now"] or "no", s["built_wave_potential"] or "no", "; ".join(s["problems"]) or "ok"))

board = [chr(10) + "## Scoreboard (recipes per chapter)" + chr(10), "| chapter | recipes | PASS | LOOKS WRONG | BLOCKER (not flagged future) | FUTURE (flagged by design) |", "|---|---|---|---|---|---|"]
for num, title, n, c in score:
    board.append("| %s %s | %d | %d | %d | %d | %d |" % (num, title, n, c["PASS"], c["LOOKS WRONG"], c["BLOCKER"], c["FUTURE"]))
out[2:2] = board
open(os.path.join(ROOT, "PLAYTHROUGH_CHAPTERS.md"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("wrote PLAYTHROUGH_CHAPTERS.md", len(out), "lines")
