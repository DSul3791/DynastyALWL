"""Writes assets/audio/CREDITS.md from CREDITS.csv: python3 assets/audio/make_credits.py

CREDITS.csv has one row per supplied recording (or family: `pattern` is a glob relative to recorded/).
Columns: pattern, what, author, source, licence, attribution (text to show players, or "none"), url, added (date).
Allowed licences: CC0, CC-BY-4.0, CC-BY-3.0, public-domain, own (your own recording), Pixabay-Content-License
(royalty-free, no attribution required, but NOT CC0: the sounds may be used inside the game but must not be redistributed
as a standalone sound pack or as separate files), or TODO until the source is known. validate_pack.py checks every file in recorded/ has a row and that no row is stale.
The generated placeholder sounds are made by the make_*.py scripts in this repository and carry no third-party material.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LICENCES = ["CC0", "CC-BY-4.0", "CC-BY-3.0", "public-domain", "own", "Pixabay-Content-License", "TODO"]


def rows():
    with open(os.path.join(HERE, "CREDITS.csv"), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    out = ["# Sound credits", "",
           "Dave's supplied recordings come from Pixabay (royalty-free, Pixabay Content License). That licence is not CC0 or CC-BY:",
           "the sounds are fine inside the game, but must not be shipped as separate files or as a standalone sound pack.", "",
           "Generated by make_credits.py from CREDITS.csv. Do not edit by hand.", "",
           "The placeholder sounds are generated by the scripts in assets/audio (no third-party material).",
           "Supplied recordings:", "", "| Sounds | Author | Source | Licence | Attribution |", "|---|---|---|---|---|"]

    for row in rows():
        out.append("| %s (`recorded/%s`) | %s | %s | %s | %s |" % (row["what"], row["pattern"], row["author"], row["source"], row["licence"], row["attribution"]))

    with open(os.path.join(HERE, "CREDITS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")

    print("Wrote CREDITS.md (%d rows)" % len(rows()))


if __name__ == "__main__":
    main()
